"""Narrow authenticated Worker service contract; no shell/systemctl/PID operation."""
from typing import Protocol, Mapping, Any

class WorkerAPI(Protocol):
    def create(self, immutable_spec: Mapping[str, Any], idempotency_key: str) -> Mapping[str, Any]: ...
    def start(self, run_id: str) -> Mapping[str, Any]: ...
    def inspect(self, run_id: str) -> Mapping[str, Any]: ...
    def cancel(self, run_id: str) -> Mapping[str, Any]: ...
    def stop(self, run_id: str) -> Mapping[str, Any]: ...
    def collect(self, run_id: str) -> Mapping[str, Any]: ...
    def cleanup(self, run_id: str) -> Mapping[str, Any]: ...
